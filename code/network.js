// the flat 41 word list, and which kind of attribute a word is
const netAttrs = [...netClubs, ...netColours, ...netTags];
function netAttrKind(word)
{
    return netClubs.includes(word) ? 0 : netColours.includes(word) ? 1 : 3;
}

// Colours near enough to read as a near miss rather than a plain miss (GDD 3),
// as one bit mask per colour in netColours order: bit k set means netColours[k]
// is a neighbour of this one. The seven bright colours are a wheel and the
// wheel wraps, so red sits beside pink; brown sits beside red and orange;
// rainbow sits beside every colour but the greys; and black, white and grey
// are a short line of their own with grey in the middle. The table is
// symmetric, which test/lib.mjs holds it to.
//
// This was twelve arrays of colour names keyed by colour, which read better
// and cost about 400 bytes of the bundle to say exactly the same thing: a
// string survives minification untouched and there were forty of them, all
// spelling words netColours already holds.
const netNear = [2242, 2181, 2058, 2068, 2088, 2128, 2081, 2051, 1024, 1024, 768, 255];

// are these two colours neighbours? either way round - the table is symmetric
function netIsNear(a, b)
{
    return netNear[netColours.indexOf(a)] >> netColours.indexOf(b) & 1;
}

