// Seeded random, so a seed reproduces a run's opinions exactly (GDD 3)
// Lehmer generator, small and good enough for rolling favorites

let netSeed = 1;

function netSetSeed(seed) { netSeed = seed%2147483647 || 1; }

function netRandInt(max)
{
    netSeed = netSeed*16807 % 2147483647;
    return netSeed % max;
}

// pick one item from an array
function netPick(list) { return list[netRandInt(list.length)]; }

///////////////////////////////////////////////////////////////////////////////

// split a string into emoji, keeping variation selectors attached to their
// glyph - iterating a string gives them as separate code points
function netSplit(text)
{
    const list = [];
    for (const c of text)
        if (c == '️' && list.length) // variation selector, invisible on its own
            list[list.length-1] += c;
        else
            list.push(c);
    return list;
}

