// split a string into emoji, keeping variation selectors attached to their
// glyph - iterating a string gives them as separate code points
function netSplit(text)
{
    const list = [];
    for (const c of text)
        if (c == '️' && list.length) // variation selector, invisible on its own
            list[list.length-1] += c;
        else
            list.push(c);
    return list;
}

