/*
    The emoji library (GDD section 3)
    - every collectible emoji carries a club, a colour, a size, and zero or
      more tags - 8 + 12 + 5 + 20 = 45 attributes, a typical emoji carries
      four or five of them
    - the library is encoded, not spelled out: emoji-data.js is the record,
      pack.mjs packs it into the strings below so the shipped copy is small
*/

