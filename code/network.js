// one integer per emoji, mixed radix then 20 tag bits, five base-64 characters
// big-endian - see pack.mjs, which builds NET_EMOJI and NET_PACK from this
const NET_ALPHA = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz$_';
let netLib = [], netByEmoji = {};

// one club's emoji, in library order - the shelf School, the keyboard, the
// exam's forced club and the starting hand all read
function netClub(club) { return netLib.filter(r => r.club == club); }

// decode NET_EMOJI/NET_PACK into netLib/netByEmoji, call once at startup
function netInit()
{
    netLib = netSplit(NET_EMOJI).map((e, i) =>
    {
        // five characters, 30 bits: a 20-bit tag mask under club, colour and
        // size (tools/pack.mjs is the other half of this layout)
        let n = 0;
        for (let j = 0; j < 5; ++j)
            n = n*64 + NET_ALPHA.indexOf(NET_PACK[i*5 + j]);
        const bits = n & 1048575; n >>= 20;
        const size = n%5; n = n/5 | 0;
        const colour = n%12, club = n/12 | 0;
        const tags = netTags.filter((t, k) => bits & 1 << k);
        return netByEmoji[e] = {e, club: netClubs[club],
            colour: netColours[colour], size: netSizes[size], tags};
    });
}
